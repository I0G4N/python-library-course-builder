def test_v4_verifier_rejects_premature_navigation_unlock(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    route_path, packages, _route = write_v4_fixture(tmp_path / "source")
    learner = tmp_path / "tiny-parser"
    scaffold_v4_pair(route_path, packages, learner)
    real_loader = verifier._load_runner_module

    @contextmanager
    def prematurely_unlocked_loader(
        learner_root: Path,
        author_root: Path,
        *,
        state_path: Path | None = None,
    ):
        with real_loader(
            learner_root,
            author_root,
            state_path=state_path,
        ) as module:
            real_exposed_state = module.exposed_state

            def expose_every_chapter(value):
                state = real_exposed_state(value)
                state["unlocked_labs"] = [
                    chapter["id"] for chapter in module.manifest()["chapters"]
                ]
                return state

            module.exposed_state = expose_every_chapter
            yield module

    monkeypatch.setattr(
        verifier,
        "_load_runner_module",
        prematurely_unlocked_loader,
    )

    with pytest.raises(V4VerificationError, match="navigation gate state"):
        verify_v4_course(learner)


def test_v4_verifier_restores_environment_and_does_not_gate_on_examples(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    route_path, packages, _route = write_v4_fixture(tmp_path / "source")
    guard = packages / "lab01/examples/optional_broken_example.py"
    guard.write_text(
        "raise RuntimeError('examples are optional acceptance artifacts')\n",
        encoding="utf-8",
    )
    learner = tmp_path / "tiny-parser"
    scaffold_v4_pair(route_path, packages, learner)
    sentinels = {
        "COURSEKIT_LEARNER_ROOT": "existing-learner",
        "COURSEKIT_ROOT": "existing-root",
        "COURSEKIT_COURSE_DIR": "existing-course-dir",
        "COURSEKIT_AUTHOR_ROOT": "existing-author",
        "COURSEKIT_STATE_PATH": "existing-state",
    }
    for name, value in sentinels.items():
        monkeypatch.setenv(name, value)
    modules_before = {
        name for name in sys.modules if name.startswith("_coursekit_v4_runtime_")
    }

    receipt = verify_v4_course(learner)

    assert receipt["passed"] is True
    assert receipt["checks"]["examples"] == {
        "count": 3,
        "executed": False,
        "required": False,
    }
    assert {name: os.environ.get(name) for name in sentinels} == sentinels
    assert {
        name for name in sys.modules if name.startswith("_coursekit_v4_runtime_")
    } == modules_before


