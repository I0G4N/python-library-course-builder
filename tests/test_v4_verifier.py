def test_v4_verifier_runs_one_red_green_and_api_acceptance(
    tmp_path: Path,
) -> None:
    route_path, packages, _route = write_v4_fixture(tmp_path / "source")
    learner = tmp_path / "tiny-parser"
    scaffold_v4_pair(route_path, packages, learner)

    receipt = verify_v4_course(learner)
    author = tmp_path / "tiny-parser-author"
    written = json.loads((author / "verification.json").read_text())

    assert receipt == written
    assert receipt["passed"] is True
    assert receipt["profile"] == "course-acceptance-v1"
    assert receipt["checks"]["starter_red"]["selectors"] == 2
    assert receipt["checks"]["solution_green"]["selectors"] == 4
    assert receipt["checks"]["starter_red"]["isolated"] is True
    assert receipt["checks"]["starter_red"]["batches"] == 1
    assert receipt["checks"]["solution_green"]["isolated"] is True
    assert receipt["checks"]["solution_green"]["batches"] == 1
    assert len(receipt["checks"]["starter_red"]["collected"]) == 2
    assert receipt["checks"]["starter_red"]["collected_count"] == 2
    assert len(receipt["checks"]["solution_green"]["collected"]) == 4
    assert receipt["checks"]["solution_green"]["collected_count"] == 4
    assert set(receipt["checks"]["starter_red"]["outcomes"].values()) == {
        "failed"
    }
    assert receipt["checks"]["starter_red"]["task_outcomes"] == {
        "lab01/lab01.q1": ["failed"],
        "lab02/lab02.q1": ["failed"],
    }
    assert set(receipt["checks"]["solution_green"]["outcomes"].values()) == {
        "passed"
    }
    assert receipt["checks"]["api_flow"]["chapters"] == 3
    assert receipt["checks"]["api_flow"]["coding_smoke"] == {
        "chapter_id": "lab01",
        "task_id": "lab01.q1",
        "runs": 2,
    }
    assert receipt["checks"]["api_flow"]["navigation_checks"] == 7
    assert receipt["checks"]["examples"]["executed"] is False
    assert receipt["checks"]["examples"]["required"] is False
    assert receipt["checks"]["node_install"] is False
    assert len(receipt["receipt_sha256"]) == 64
    verifier_script = SKILL_ROOT / "scripts/verify_v4_course.py"
    assert receipt["verifier_sha256"] != hashlib.sha256(
        verifier_script.read_bytes()
    ).hexdigest()
    assert validate_v4_receipt(learner) == receipt

    dispatched = verify(learner, full=True)
    assert dispatched["passed"] is True
    assert dispatched["per_course_node_checks"] is False
    assert dispatched["full_reused_shared_engine_conformance"] is True

    state_path = learner / ".coursekit/state.json"
    with _load_runner_module(
        learner,
        author,
        state_path=state_path,
    ) as module, TestClient(module.create_app()) as client:
        answered = client.post(
            "/api/knowledge/answer",
            json={
                "lab_id": "lab00",
                "question_id": "lab00.k1",
                "choice_id": "a",
            },
        )
        assert answered.status_code == 200
        assert answered.json()["correct"] is True
    assert state_path.is_file()
    assert state_path.with_name("state.json.lock").is_file()
    assert validate_v4_receipt(learner) == receipt

    metadata = learner / "tiny_parser.egg-info/PKG-INFO"
    metadata.parent.mkdir()
    metadata.write_text("Generated by learner environment setup.\n", encoding="utf-8")
    assert validate_v4_receipt(learner) == receipt

    lock = learner / "uv.lock"
    lock.write_text(
        "version = 1\nrevision = 3\n",
        encoding="utf-8",
    )
    with pytest.raises(V4VerificationError, match="learner_tree_sha256"):
        validate_v4_receipt(learner)


def test_v4_verifier_tests_cannot_mutate_learner_or_canonical_tests(
    tmp_path: Path,
) -> None:
    route_path, packages, _route = write_v4_fixture(tmp_path / "source")
    public_test = packages / "lab01/tests/public/test_normalize.py"
    public_test.write_text(
        public_test.read_text(encoding="utf-8").replace(
            "def test_normalize():\n",
            "def test_normalize():\n"
            "    from pathlib import Path\n"
            "    Path('src/tiny_parser/normalize.py').write_text("
            "'MUTATED = True\\n')\n"
            "    Path('LEARNER_TEST_RAN').write_text('bad')\n"
            "    Path(__file__).with_name('CANONICAL_TEST_MUTATED').write_text("
            "'bad')\n",
        ),
        encoding="utf-8",
    )
    learner = tmp_path / "tiny-parser"
    scaffold_v4_pair(route_path, packages, learner)
    starter = learner / "src/tiny_parser/normalize.py"
    canonical = learner / "tests/lab01/test_normalize.py"
    starter_before = starter.read_bytes()
    canonical_before = canonical.read_bytes()

    receipt = verify_v4_course(learner)

    assert receipt["passed"] is True
    assert starter.read_bytes() == starter_before
    assert canonical.read_bytes() == canonical_before
    assert not (learner / "LEARNER_TEST_RAN").exists()
    assert not (
        learner / "tests/lab01/CANONICAL_TEST_MUTATED"
    ).exists()


